"""Generate web and TypeScript token exports from the canonical JSON."""
import hashlib
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1] / 'kit'
tokens = json.loads((root / 'tokens.json').read_text())
lines = ['/* Generated by scripts/build.py; edit tokens.json. */']
for theme in ['light', 'dark']:
    selector = ':root, [data-dot-theme="light"]' if theme == 'light' else '[data-dot-theme="dark"]'
    lines.append(selector + ' {')
    for key, value in tokens['colors'][theme].items():
        lines.append(f'  --dot-{key}: {value};')
    accents = tokens['colors']['accents' if theme == 'light' else 'accentsDark']
    for key, value in accents.items():
        lines.append(f'  --dot-accent-{key}: {value};')
    lines.append(f"  --dot-on-accent: {tokens['colors']['onAccent'][theme]};")
    if theme == 'light':
        lines.append(f"  --dot-pressed-opacity: {tokens['interaction']['pressedOpacity']};")
        for key, value in tokens['spacing'].items():
            lines.append(f'  --dot-space-{key}: {value}px;')
        for key, value in tokens['radius'].items():
            lines.append(f'  --dot-radius-{key}: {value}px;')
        for key, value in tokens['motion'].items():
            if key.endswith('Ms'):
                lines.append(f'  --dot-{key}: {value}ms;')
    lines.append('}')
(root / 'tokens.css').write_text('\n'.join(lines) + '\n')
(root / 'tokens.ts').write_text('// Generated by scripts/build.py; edit tokens.json.\nexport const dotTokens = ' + json.dumps(tokens, indent=2) + ' as const;\n')

# Documentation policies have their own manifest; token values are unchanged.
policy_files = ('AGENT_DEVELOPMENT.md', 'TOOL_CATALOG.md', 'LOCALIZATION.md',
                'APP_STORE_PLAYBOOK.md', 'TREND_RESEARCH.md', 'LANGUAGES.json')
repo = root.parent
manifest = {'schemaVersion': 1, 'policyVersion': 3, 'files': {
    name: {'path': 'docs/' + name, 'sha256': hashlib.sha256((repo / 'docs' / name).read_bytes()).hexdigest()}
    for name in policy_files}}
(repo / 'agent-policy').mkdir(exist_ok=True)
(repo / 'agent-policy/manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
