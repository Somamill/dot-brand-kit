"""Generate web and TypeScript token exports from the canonical JSON."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1] / 'kit'
tokens = json.loads((root / 'tokens.json').read_text())
lines = ['/* Generated by scripts/build.py; edit tokens.json. */']
for theme in ['light', 'dark']:
    selector = ':root, [data-dot-theme="light"]' if theme == 'light' else '[data-dot-theme="dark"]'
    lines.append(selector + ' {')
    for key, value in tokens['colors'][theme].items():
        lines.append(f'  --dot-{key}: {value};')
    if theme == 'light':
        for key, value in tokens['spacing'].items():
            lines.append(f'  --dot-space-{key}: {value}px;')
        for key, value in tokens['radius'].items():
            lines.append(f'  --dot-radius-{key}: {value}px;')
        for key, value in tokens['colors']['accents'].items():
            lines.append(f'  --dot-accent-{key}: {value};')
    lines.append('}')
(root / 'tokens.css').write_text('\n'.join(lines) + '\n')
(root / 'tokens.ts').write_text('// Generated by scripts/build.py; edit tokens.json.\nexport const dotTokens = ' + json.dumps(tokens, indent=2) + ' as const;\n')
